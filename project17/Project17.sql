-- ENTERPRISE GOVERNANCE VIA ROLE-AWARE SECURE VIEW
USE ROLE ACCOUNTADMIN;
USE DATABASE FINANCIAL_GOVERNANCE_DB;
USE SCHEMA WEALTH_CORE;

CREATE OR REPLACE SECURE VIEW V_SILVER_BANK_TRANSACTIONS AS
SELECT 
    TXN_ID,
    CLIENT_ID,
   
    CASE 
        WHEN CURRENT_ROLE() IN ('COMPLIANCE_OFFICER', 'ACCOUNTADMIN') THEN CLIENT_SSN
        ELSE '***-**-' || RIGHT(CLIENT_SSN, 4)
    END AS CLIENT_SSN,
    REGION,
  
    CASE 
        WHEN CURRENT_ROLE() IN ('COMPLIANCE_OFFICER', 'ACCOUNTADMIN') THEN ACCOUNT_NO
        ELSE LEFT(ACCOUNT_NO, 4) || '****'
    END AS ACCOUNT_NO,
    AMOUNT,
    STATUS,
    AML_RISK_SCORE
FROM SILVER_BANK_TRANSACTIONS
WHERE 
    CURRENT_ROLE() IN ('COMPLIANCE_OFFICER', 'ACCOUNTADMIN')
    OR (CURRENT_ROLE() = 'NA_ANALYST' AND REGION = 'NA')
    OR (CURRENT_ROLE() = 'EU_ANALYST' AND REGION = 'EU');

GRANT SELECT ON VIEW V_SILVER_BANK_TRANSACTIONS TO ROLE COMPLIANCE_OFFICER;
GRANT SELECT ON VIEW V_SILVER_BANK_TRANSACTIONS TO ROLE NA_ANALYST;
GRANT SELECT ON VIEW V_SILVER_BANK_TRANSACTIONS TO ROLE EU_ANALYST;


USE ROLE NA_ANALYST;
USE WAREHOUSE COMPUTE_WH;
USE DATABASE FINANCIAL_GOVERNANCE_DB;
USE SCHEMA WEALTH_CORE;

SELECT 
    TXN_ID,
    CLIENT_ID,
    CLIENT_SSN,
    REGION,
    ACCOUNT_NO,
    AMOUNT,
    STATUS,
    AML_RISK_SCORE
FROM V_SILVER_BANK_TRANSACTIONS
ORDER BY TXN_ID;


-- SECURE DATA SHARING & CLEAN ROOM AUDIT VIEW
USE ROLE ACCOUNTADMIN;
USE DATABASE FINANCIAL_GOVERNANCE_DB;
USE SCHEMA WEALTH_CORE;

CREATE OR REPLACE SECURE VIEW SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY AS
SELECT 
    REGION,
    SUM(AMOUNT) AS TOTAL_SETTLED_VAL,
    COUNT(*) AS SETTLED_TXN_COUNT,
    ROUND(AVG(AMOUNT), 2) AS AVG_SETTLED_AMOUNT
FROM SILVER_BANK_TRANSACTIONS
WHERE STATUS = 'SETTLED'
GROUP BY REGION;

GRANT SELECT ON VIEW SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY TO ROLE COMPLIANCE_OFFICER;
GRANT SELECT ON VIEW SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY TO ROLE NA_ANALYST;
GRANT SELECT ON VIEW SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY TO ROLE EU_ANALYST;

-- Task 5 Verification Query (Executed as ACCOUNTADMIN or COMPLIANCE_OFFICER)
SELECT 
    REGION,
    TOTAL_SETTLED_VAL,
    SETTLED_TXN_COUNT,
    AVG_SETTLED_AMOUNT
FROM SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY
ORDER BY REGION;


-- END-TO-END GOVERNANCE AUDIT & LINEAGE RECONCILIATION
USE ROLE COMPLIANCE_OFFICER;
USE WAREHOUSE COMPUTE_WH;
USE DATABASE FINANCIAL_GOVERNANCE_DB;
USE SCHEMA WEALTH_CORE;

SELECT 
    (
        SELECT SUM(PAYLOAD:amount::NUMBER(12,2)) 
        FROM BRONZE_BANK_PAYLOADS
    ) AS BRONZE_GROSS_TOTAL,
    (
        SELECT SUM(AMOUNT) 
        FROM SILVER_BANK_TRANSACTIONS
    ) AS SILVER_GROSS_TOTAL,
    (
        SELECT SUM(TOTAL_SETTLED_VAL) 
        FROM SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY
    ) AS GOLD_GROSS_TOTAL,
    CASE 
        WHEN (
            SELECT SUM(PAYLOAD:amount::NUMBER(12,2)) 
            FROM BRONZE_BANK_PAYLOADS
        ) = (
            SELECT SUM(AMOUNT) 
            FROM SILVER_BANK_TRANSACTIONS
        )
        THEN TRUE 
        ELSE FALSE 
    END AS RECONCILED_FLAG;