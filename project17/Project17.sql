USE DATABASE FINANCIAL_GOVERNANCE_DB;
USE SCHEMA WEALTH_CORE;


CREATE OR REPLACE FILE FORMAT RAW_TEXT_FF
    TYPE = 'CSV'
    RECORD_DELIMITER = '\n'
    FIELD_DELIMITER = 'NONE';

CREATE OR REPLACE STAGE BANKING_STAGE;


CREATE OR REPLACE TABLE STG_RAW_INPUT (
    RAW_LINE VARCHAR);


COPY INTO STG_RAW_INPUT 
FROM @BANKING_STAGE
FILE_FORMAT = RAW_TEXT_FF
PATTERN = '.*banking_batch.*[.]json'
FORCE = TRUE;


CREATE OR REPLACE TABLE BRONZE_BANK_PAYLOADS (
    INGEST_ID NUMBER AUTOINCREMENT PRIMARY KEY,
    PAYLOAD VARIANT,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());


INSERT INTO BRONZE_BANK_PAYLOADS (PAYLOAD)
SELECT PARSE_JSON(RAW_LINE)
FROM STG_RAW_INPUT
WHERE TRY_PARSE_JSON(RAW_LINE) IS NOT NULL 
  AND PARSE_JSON(RAW_LINE):txn_id IS NOT NULL;


SELECT COUNT(*) AS TOTAL_BRONZE_RECORDS FROM BRONZE_BANK_PAYLOADS;


CREATE OR REPLACE TABLE QUARANTINE_GOVERNANCE_PAYLOADS (
    QUARANTINE_ID NUMBER AUTOINCREMENT PRIMARY KEY,
    RAW_RECORD_TEXT VARCHAR,
    REASON VARCHAR(100),
    QUARANTINED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());


INSERT INTO QUARANTINE_GOVERNANCE_PAYLOADS (RAW_RECORD_TEXT, REASON)
SELECT 
    RAW_LINE,
    'MALFORMED_JSON_BODY' AS REASON
FROM STG_RAW_INPUT
WHERE TRY_PARSE_JSON(RAW_LINE) IS NULL 
   OR PARSE_JSON(RAW_LINE):txn_id IS NULL;


SELECT 
    QUARANTINE_ID,
    RAW_RECORD_TEXT,
    REASON
FROM QUARANTINE_GOVERNANCE_PAYLOADS;


--  SILVER LAYER SETUP & RBAC ROLE PROVISIONING
CREATE OR REPLACE TABLE SILVER_BANK_TRANSACTIONS (
    TXN_ID VARCHAR(30) PRIMARY KEY,
    CLIENT_ID NUMBER,
    CLIENT_SSN VARCHAR(30),
    REGION VARCHAR(10),
    ACCOUNT_NO VARCHAR(30),
    AMOUNT NUMBER(12,2),
    STATUS VARCHAR(20),
    AML_RISK_SCORE VARCHAR(20));


INSERT INTO SILVER_BANK_TRANSACTIONS (
    TXN_ID,
    CLIENT_ID,
    CLIENT_SSN,
    REGION,
    ACCOUNT_NO,
    AMOUNT,
    STATUS,
    AML_RISK_SCORE)
SELECT 
    PAYLOAD:txn_id::VARCHAR AS TXN_ID,
    PAYLOAD:client_id::NUMBER AS CLIENT_ID,
    PAYLOAD:client_ssn::VARCHAR AS CLIENT_SSN,
    PAYLOAD:region::VARCHAR AS REGION,
    PAYLOAD:account_no::VARCHAR AS ACCOUNT_NO,
    PAYLOAD:amount::NUMBER(12,2) AS AMOUNT,
    PAYLOAD:status::VARCHAR AS STATUS,
    PAYLOAD:aml_risk_score::VARCHAR AS AML_RISK_SCORE
FROM BRONZE_BANK_PAYLOADS;


SELECT COUNT(*) AS TOTAL_SILVER_RECORDS FROM SILVER_BANK_TRANSACTIONS;

