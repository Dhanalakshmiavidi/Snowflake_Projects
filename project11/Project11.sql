SELECT 'CURRENT RECORD COUNT', COUNT(*) 
FROM DIM_CUSTOMER_HYBRID 
WHERE IS_CURRENT = TRUE
UNION ALL
SELECT 'HISTORICAL RECORD COUNT', COUNT(*) 
FROM DIM_CUSTOMER_HYBRID 
WHERE IS_CURRENT = FALSE;